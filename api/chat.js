// ------- 日替わり当番の決定(日本時間0時に交代) -------
const ROTATION = ["kanato", "shogo", "gaku", "yuichi"];
function todaysMemberId() {
  const jstDayNumber = Math.floor((Date.now() + 9 * 3600 * 1000) / 86400000);
  return ROTATION[jstDayNumber % ROTATION.length];
}

